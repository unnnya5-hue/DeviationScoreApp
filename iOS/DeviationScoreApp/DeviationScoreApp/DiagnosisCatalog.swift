    private static func choice(_ id: String, _ text: String, _ options: [AnswerOption]) -> DiagnosisQuestion {
        DiagnosisQuestion(id: id, text: text, input: .choice(options))
    }

    private static func number(
        _ id: String,
        _ text: String,
        unit: String,
        scoring: NumericScoringRule
    ) -> DiagnosisQuestion {
        DiagnosisQuestion(
            id: id,
            text: text,
            input: .number(
                NumericQuestionConfig(
                    placeholder: "",
                    unit: unit,
                    helperText: "",
                    scoring: scoring
                )
            )
        )
    }

    private static func options(_ choices: (String, String, Int)...) -> [AnswerOption] {
        choices.map { choice in
            AnswerOption(id: choice.0, text: choice.1, point: choice.2)
        }
    }
